"""Generate a deterministic Unicode BMP -> GB2312 mapping from Python's codec."""
from pathlib import Path
root = Path(__file__).resolve().parent.parent
entries = []
for point in range(0x80, 0x10000):
    try:
        encoded = chr(point).encode('gb2312')
    except UnicodeEncodeError:
        continue
    if len(encoded) == 2:
        entries.append((point, int.from_bytes(encoded, 'big')))
assert len(entries) == 7445
lines = ['// Generated by scripts/generate_gb2312.py from the GB2312 codec.\n#pragma once\n#include <cstdint>\n#if defined(ARDUINO_ARCH_ESP8266)\n#include <pgmspace.h>\n#define CLOCK_GB_FLASH PROGMEM\n#else\n#define CLOCK_GB_FLASH\n#endif\nnamespace clockapp::encoding {\nstruct Mapping { uint16_t unicode, gb; };\ninline constexpr Mapping gb2312[] CLOCK_GB_FLASH = {\n']
for index in range(0, len(entries), 6):
    lines.append('  ' + ','.join(f'{{0x{u:04x},0x{g:04x}}}' for u, g in entries[index:index+6]) + ',\n')
lines.append('''};
inline Mapping gb2312At(unsigned index) {
#if defined(ARDUINO_ARCH_ESP8266)
  return {pgm_read_word(&gb2312[index].unicode), pgm_read_word(&gb2312[index].gb)};
#else
  return gb2312[index];
#endif
}
}
#undef CLOCK_GB_FLASH
''')
(root / 'include/clock/gb2312_table.h').write_text(''.join(lines))
print(f'Generated {len(entries)} GB2312 mappings')
