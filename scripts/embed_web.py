"""Embed offline web assets; usable standalone and as a PlatformIO pre-script."""
from pathlib import Path

if "__file__" in globals():
    root = Path(__file__).resolve().parent.parent
else:
    Import("env")  # SCons provides this function when used as a pre-script.
    root = Path(env["PROJECT_DIR"])
target = root / "include/clock/web_assets.h"
parts = ["// Generated by scripts/embed_web.py; edit web/ source files instead.\n#pragma once\n#if defined(ARDUINO_ARCH_ESP8266)\n#include <pgmspace.h>\n#define CLOCK_WEB_FLASH PROGMEM\n#else\n#define CLOCK_WEB_FLASH\n#endif\nnamespace clockapp::web {\n"]
for name, filename in [("index", "index.html"), ("style", "style.css"), ("app", "app.js")]:
    source = (root / "web" / filename).read_text(encoding="utf-8")
    if ')VFDWEB"' in source:
        raise ValueError("Asset contains the C++ raw-string delimiter")
    parts.append(f'inline constexpr char {name}[] CLOCK_WEB_FLASH = R"VFDWEB({source})VFDWEB";\n')
parts.append("}\n#undef CLOCK_WEB_FLASH\n")
content = "".join(parts)
if not target.exists() or target.read_text(encoding="utf-8") != content:
    target.write_text(content, encoding="utf-8")
